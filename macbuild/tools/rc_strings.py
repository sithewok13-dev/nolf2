#!/usr/bin/env python3
"""Turn the STRINGTABLEs of NOLF2's cres.dll sources into a C++ table.

cres.dll (NOLF2/ClientRes) is a Win32 resource DLL that holds the game's
interface text. The macOS / iOS port reads the player's own cres.dll
(runtime/kernel/src/sys/macos/macos_cres.cpp); when that file is not found it
falls back to this table, built from the same sources in this repository, so
the game still has its menu text -- and a default profile name, without which
CProfileMgr::Init fails and the game stops before the menu.

    rc_strings.py OUT.cpp HEADER.h... -- FILE.rc...

The strings are stored the way macos_cres.cpp stores the ones it reads out of
cres.dll: Windows-1252 decoded, then each character narrowed to one byte
(Latin-1), anything above U+00FF as '?'.
"""
import re
import sys

ESCAPES = {'n': '\n', 't': '\t', 'r': '\r', 'a': '\a', '\\': '\\', '"': '"', "'": "'"}


def read_text(path):
    with open(path, 'rb') as f:
        return f.read().decode('cp1252', errors='replace')


def read_defines(paths):
    defs = {}
    for p in paths:
        for m in re.finditer(r'^\s*#\s*define\s+(\w+)\s+(\d+)\b', read_text(p), re.M):
            defs[m.group(1)] = int(m.group(2))
    return defs


def unescape(body):
    """The inside of one RC string literal ("" is a quote)."""
    out, i = [], 0
    while i < len(body):
        c = body[i]
        if c == '"' and body[i + 1:i + 2] == '"':
            out.append('"'); i += 2; continue
        if c == '\\' and i + 1 < len(body):
            n = body[i + 1]
            if n in ESCAPES:
                out.append(ESCAPES[n]); i += 2; continue
            if n in 'xX':
                m = re.match(r'[0-9a-fA-F]{1,4}', body[i + 2:])
                if m:
                    out.append(chr(int(m.group(0), 16))); i += 2 + len(m.group(0)); continue
            if n in '01234567':
                m = re.match(r'[0-7]{1,3}', body[i + 1:])
                out.append(chr(int(m.group(0), 8))); i += 1 + len(m.group(0)); continue
            out.append(n); i += 2; continue
        out.append(c); i += 1
    return ''.join(out)


TOKEN = re.compile(r'''
    (?P<ws>\s+|//[^\n]*|/\*.*?\*/)
  | (?P<str>L?"(?:[^"]|"")*")
  | (?P<comma>,)
  | (?P<word>[A-Za-z_]\w*|\d+)
''', re.X | re.S)


def parse_tables(text, defs, table, path):
    for block in re.finditer(r'\bSTRINGTABLE\b[^\n]*\n\s*(?:BEGIN|\{)(.*?)^\s*(?:END|\})\s*$',
                             text, re.S | re.M):
        body, pos, cur_id, cur = block.group(1), 0, None, None

        def flush():
            if cur_id is not None and cur is not None:
                table[cur_id] = cur

        while pos < len(body):
            m = TOKEN.match(body, pos)
            if not m:
                raise SystemExit('%s: cannot parse near %r' % (path, body[pos:pos + 40]))
            pos = m.end()
            if m.group('ws') or m.group('comma'):
                continue
            if m.group('word'):
                flush()
                w = m.group('word')
                if w.isdigit():
                    cur_id = int(w)
                elif w in defs:
                    cur_id = defs[w]
                else:
                    raise SystemExit('%s: unknown string id %s' % (path, w))
                cur = None
            else:
                lit = m.group('str')
                lit = lit[2:-1] if lit.startswith('L') else lit[1:-1]
                cur = (cur or '') + unescape(lit)
        flush()


def narrow(s):
    return bytes((ord(c) if ord(c) < 0x100 else ord('?')) for c in s)


def c_literal(b):
    out = []
    for x in b:
        ch = chr(x)
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= x < 0x7F and ch != '?':   # '?' escaped: no trigraphs
            out.append(ch)
        else:
            out.append('\\%03o' % x)
    return '"' + ''.join(out) + '"'


def main(argv):
    if len(argv) < 4 or '--' not in argv:
        raise SystemExit(__doc__)
    out = argv[1]
    sep = argv.index('--')
    headers, rcs = argv[2:sep], argv[sep + 1:]
    defs = read_defines(headers)
    table = {}
    for rc in rcs:       # later files win, as later STRINGTABLE entries would
        parse_tables(read_text(rc), defs, table, rc)
    if not table:
        raise SystemExit('no strings found')
    lines = [
        '// GENERATED by macbuild/tools/rc_strings.py from the cres.dll sources',
        '// (NOLF2/ClientRes). Do not edit; edit the .rc files.',
        '#include "macos_cres.h"',
        '',
        'extern const LTBuiltinCResString g_aLTBuiltinCRes[] = {',
    ]
    for nid in sorted(table):
        lines.append('\t{ %du, %s },' % (nid, c_literal(narrow(table[nid]))))
    lines += ['};', 'extern const unsigned int g_nLTBuiltinCRes = %d;' % len(table), '']
    with open(out, 'w', encoding='ascii') as f:
        f.write('\n'.join(lines))
    print('rc_strings: %d strings -> %s' % (len(table), out))


if __name__ == '__main__':
    main(sys.argv)
